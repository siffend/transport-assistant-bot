# Термины, которые нельзя резать стеммером (аббревиатуры, названия).
KEEP_AS_IS = {"стк", "мфц", "оеирц", "нпа", "мир", "nfc", "гу", "то", "мкп"}

_TOKEN_RE = re.compile(r"[а-яa-z0-9]+", re.IGNORECASE)

# Синонимы на уровне основ: «грязно», «грязного» и «грязный» приводятся
# к одной основе и подхватывают замену, заданную для словарной формы.
SYNONYM_STEMS = {}
for _k, _v in SYNONYMS.items():
    _ks = _k if _k in KEEP_AS_IS else stem(_k)
    _vs = _v if _v in KEEP_AS_IS else stem(_v)
    if _ks != _vs:
        SYNONYM_STEMS.setdefault(_ks, _vs)


def tokenize(text: str) -> List[str]:
    """Разбивает текст на нормализованные токены."""
    text = (text or "").lower().replace("ё", "е")
    raw = _TOKEN_RE.findall(text)
    out: List[str] = []
    for tok in raw:
        tok = SYNONYMS.get(tok, tok)
        if tok in STOPWORDS:
            continue
        if len(tok) < 2 and not tok.isdigit():
            continue
        base = tok if tok in KEEP_AS_IS else stem(tok)
        out.append(SYNONYM_STEMS.get(base, base))
    return out


def char_ngrams(text: str, n: int = 3) -> List[str]:
    """Символьные n-граммы — устойчивость к опечаткам и словоформам."""
    text = " " + re.sub(r"\s+", " ", (text or "").lower().replace("ё", "е").strip()) + " "
    if len(text) <= n:
        return [text]
    return [text[i : i + n] for i in range(len(text) - n + 1)]


_PREFIX_CACHE: dict = {}


def has_keyword(text: str, keyword: str) -> bool:
    """Совпадение по началу слова: «город» не находится внутри «пригород»."""
    low = (text or "").lower().replace("ё", "е")
    kw = (keyword or "").lower().replace("ё", "е").strip()
    if not kw:
        return False
    pattern = _PREFIX_CACHE.get(kw)
    if pattern is None:
        pattern = re.compile(r"(?<![а-яa-z0-9])" + re.escape(kw))
        _PREFIX_CACHE[kw] = pattern
    return bool(pattern.search(low))


def contains_any(text: str, words: Iterable[str]) -> bool:
    return any(has_keyword(text, w) for w in words)
