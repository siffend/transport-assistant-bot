# --------------------------------------------------------------------------
# Стеммер Портера для русского языка
# --------------------------------------------------------------------------

_VOWELS = "аеиоуыэюя"

_PERFECTIVE_GROUND = re.compile(
    r"((ив|ивши|ившись|ыв|ывши|ывшись)|((?<=[ая])(в|вши|вшись)))$"
)
_REFLEXIVE = re.compile(r"(с[яь])$")
_ADJECTIVE = re.compile(
    r"(ее|ие|ые|ое|ими|ыми|ей|ий|ый|ой|ем|им|ым|ом|его|ого|ему|ому|их|ых|ую|юю|ая|яя|ою|ею)$"
)
_PARTICIPLE = re.compile(r"((ивш|ывш|ующ)|((?<=[ая])(ем|нн|вш|ющ|щ)))$")
_VERB = re.compile(
    r"((ила|ыла|ена|ейте|уйте|ите|или|ыли|ей|уй|ил|ыл|им|ым|ен|ило|ыло|ено|ят|ует|уют|ит|ыт|ены|ить|ыть|ишь|ую|ю)"
    r"|((?<=[ая])(ла|на|ете|йте|ли|й|л|ем|н|ло|но|ет|ют|ны|ть|ешь|нно)))$"
)
_NOUN = re.compile(
    r"(а|ев|ов|ие|ье|е|иями|ями|ами|еи|ии|и|ией|ей|ой|ий|й|иям|ям|ием|ем|ам|ом|о|у|ах|иях|ях|ы|ь|ию|ью|ю|ия|ья|я)$"
)
_SUPERLATIVE = re.compile(r"(ейше|ейш)$")
_DERIVATIONAL = re.compile(r".*[^аеиоуыэюя]+[аеиоуыэюя].*ость?$")
_DER = re.compile(r"ость?$")
_I = re.compile(r"и$")
_P = re.compile(r"ь$")
_NN = re.compile(r"нн$")


def stem(word: str) -> str:
    """Возвращает основу русского слова (стеммер Портера)."""
    word = word.replace("ё", "е")
    if len(word) <= 3 or not any(ch in _VOWELS for ch in word):
        return word

    # RV — часть слова после первой гласной
    m = re.match(r"^(.*?[аеиоуыэюя])(.*)$", word)
    if not m:
        return word
    pre, rv = m.group(1), m.group(2)

    temp = _PERFECTIVE_GROUND.sub("", rv, count=1)
    if temp == rv:
        rv = _REFLEXIVE.sub("", rv, count=1)
        temp = _ADJECTIVE.sub("", rv, count=1)
        if temp != rv:
            rv = temp
            rv = _PARTICIPLE.sub("", rv, count=1)
        else:
            temp = _VERB.sub("", rv, count=1)
            rv = temp if temp != rv else _NOUN.sub("", rv, count=1)
    else:
        rv = temp

    rv = _I.sub("", rv, count=1)
    if _DERIVATIONAL.match(rv):
        rv = _DER.sub("", rv, count=1)
    temp = _P.sub("", rv, count=1)
    if temp == rv:
        rv = _SUPERLATIVE.sub("", rv, count=1)
        rv = _NN.sub("н", rv, count=1)
    else:
        rv = temp
    return pre + rv


